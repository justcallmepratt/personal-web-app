import type { Metadata } from 'next'

// Single source for the site's identity, used by metadata, robots, sitemap,
// the Open Graph image and JSON-LD so they cannot drift apart.

export const DEFAULT_SITE_URL = 'https://justcallmepratt.dev'
export const DEFAULT_SITE_NAME = 'V // Night City Dev'

/**
 * Normalises NEXT_PUBLIC_SITE_URL to an origin without a trailing slash.
 * Unset, blank, non-http(s) or unparsable values fall back to the production
 * address rather than breaking the build or emitting a wrong canonical host.
 */
export function resolveSiteUrl(raw: string | undefined): string {
  const value = raw?.trim()
  if (!value) return DEFAULT_SITE_URL
  try {
    const url = new URL(value)
    if (url.protocol !== 'https:' && url.protocol !== 'http:') return DEFAULT_SITE_URL
    return url.origin
  } catch {
    return DEFAULT_SITE_URL
  }
}

export const siteUrl = resolveSiteUrl(process.env.NEXT_PUBLIC_SITE_URL)
export const siteName = process.env.NEXT_PUBLIC_SITE_NAME?.trim() || DEFAULT_SITE_NAME
export const siteDescription =
  'Full-stack engineer — Java, Spring Boot, React, Next.js. Night City protocols.'

/** Public, indexable routes. `/api/*` is deliberately absent. */
export const publicRoutes = ['/', '/experience', '/projects', '/skills', '/contact', '/credits'] as const
export type PublicRoute = (typeof publicRoutes)[number]

/** Absolute URL for a site path; the home page has no trailing slash. */
export function absoluteUrl(path: string = '/'): string {
  const clean = path.replace(/^\/+|\/+$/g, '')
  return clean ? `${siteUrl}/${clean}` : siteUrl
}

interface PageMeta {
  /** Page title without the site name; omit on the home page. */
  title?: string
  description: string
  path: PublicRoute
}

/** The build-time image generated by src/app/opengraph-image.tsx. */
export const socialImage = { url: '/opengraph-image', width: 1200, height: 630, alt: siteName, type: 'image/png' }

/**
 * Metadata for one page: its own title, description, canonical link and
 * matching Open Graph / Twitter text. Metadata merges shallowly across
 * segments, so `openGraph` and `twitter` are restated in full here, image
 * included: a page that sets `openGraph` would otherwise lose the root image.
 */
export function pageMetadata({ title, description, path }: PageMeta): Metadata {
  const socialTitle = title ? `${title} | ${siteName}` : siteName
  return {
    ...(title ? { title } : {}),
    description,
    alternates: { canonical: path },
    openGraph: {
      title: socialTitle,
      description,
      url: path,
      siteName,
      type: 'website',
      locale: 'en_US',
      images: [socialImage],
    },
    twitter: {
      card: 'summary_large_image',
      title: socialTitle,
      description,
      images: [socialImage],
    },
  }
}

export const rootMetadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title: { default: siteName, template: `%s | ${siteName}` },
  applicationName: siteName,
  ...pageMetadata({ description: siteDescription, path: '/' }),
}

/** Minimal structured data: the site itself, no person details (content is placeholder). */
export const websiteJsonLd = {
  '@context': 'https://schema.org',
  '@type': 'WebSite',
  name: siteName,
  url: absoluteUrl('/'),
  description: siteDescription,
  inLanguage: 'en',
} as const
